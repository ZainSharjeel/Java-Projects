class Adding {

    public static int add(int a, int b) {
        return a + b;
    }

    public static double add(int a, int b, int c) {
        return a + b;
    }
}

    public class MethodOverloading {

        public static void main(String[] args) {

            System.out.println(Adding.add(5, 5));

        }
    }
